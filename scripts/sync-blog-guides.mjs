#!/usr/bin/env node
// Generates lib/blogGuides.js: shop category slug -> up to 3 matching guides on
// the blog (preisgucken.com). Source of truth is lib/blogCategories.ts in the
// blog repo (each post's `pgLink` names the shop category it belongs to).
//
//   node scripts/sync-blog-guides.mjs [path/to/preisgucken_com/lib/blogCategories.ts]
//
// Re-run it after adding blog posts, then commit lib/blogGuides.js.
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const src = process.argv[2] || join(homedir(), "Documents/preisgucken_com/lib/blogCategories.ts");
const text = readFileSync(src, "utf8");
const posts = [...text.matchAll(/\{ slug: "([^"]+)", title: "([^"]*)".*?pgLink: "([^"]*)"/g)].map((m) => ({
  slug: m[1],
  title: m[2].replace(/\\"/g, '"'),
  pg: m[3].split(",").map((s) => s.trim()).filter(Boolean),
}));
const map = {};
for (const p of posts) for (const s of p.pg) (map[s] ||= []).push({ title: p.title, url: `https://www.preisgucken.com/blog/${p.slug}/` });
for (const k of Object.keys(map)) map[k] = map[k].slice(0, 3);
const out = `// GENERATED by scripts/sync-blog-guides.mjs from the blog repo - do not edit by hand.
// shop category slug -> matching guides on preisgucken.com (shown on category pages).
export const BLOG_GUIDES = ${JSON.stringify(map, null, 2)};
`;
writeFileSync(join(process.cwd(), "lib/blogGuides.js"), out);
console.log(`${posts.length} posts -> guides for ${Object.keys(map).length} categories written to lib/blogGuides.js`);
